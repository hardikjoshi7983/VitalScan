from reportlab.lib.pagesizes import letter
from reportlab.pdfgen import canvas
from reportlab.lib import colors
from reportlab.lib.units import inch
import datetime

def create_prescription_pdf(patient_name, scores, filename="Patient_Report.pdf"):
    c = canvas.Canvas(filename, pagesize=letter)
    width, height = letter

    # --- Header ---
    c.setFont("Helvetica-Bold", 20)
    c.drawString(1 * inch, height - 1 * inch, "Health Analytics Report")
    
    c.setFont("Helvetica", 12)
    c.drawString(1 * inch, height - 1.3 * inch, f"Patient Name: {patient_name}")
    c.drawString(1 * inch, height - 1.5 * inch, f"Date: {datetime.date.today().strftime('%B %d, %Y')}")
    
    # Line separator
    c.setStrokeColor(colors.grey)
    c.line(1 * inch, height - 1.6 * inch, width - 1 * inch, height - 1.6 * inch)

    # --- Body ---
    y_position = height - 2 * inch
    
    c.setFont("Helvetica-Bold", 14)
    c.drawString(1 * inch, y_position, "Model Predictions & Analysis:")
    y_position -= 0.4 * inch

    # Loop through the scores from the pipeline
    for pattern, data in scores.items():
        display_name = pattern.replace('_', ' ').title()
        
        c.setFont("Helvetica-Bold", 12)
        c.drawString(1.2 * inch, y_position, f"{display_name}")
        
        c.setFont("Helvetica", 12)
        c.drawString(4 * inch, y_position, f"Model Score: {data['model_score']}%")
        c.drawString(5.5 * inch, y_position, f"Remaining: {data['remaining']}%")
        
        y_position -= 0.2 * inch
        c.setFont("Helvetica-Oblique", 10)
        
        context = get_context_for_pattern(pattern)
        c.drawString(1.4 * inch, y_position, f"Context: {context}")
        
        y_position -= 0.4 * inch

    # --- Disclaimer ---
    c.setFont("Helvetica-Bold", 10)
    c.setFillColor(colors.red)
    c.drawString(1 * inch, 1.5 * inch, "DISCLAIMER:")
    c.setFont("Helvetica", 9)
    c.setFillColor(colors.black)
    c.drawString(1 * inch, 1.35 * inch, "This report is generated by experimental AI models (Keras ANN & Transformers).")
    c.drawString(1 * inch, 1.2 * inch, "It does not constitute a medical diagnosis. Please consult a licensed physician.")

    c.save()
    return filename

def get_context_for_pattern(pattern):
    contexts = {
        "bmi_pattern": "BMI itself does not cause a specific symptom and cannot determine health on its own.",
        "heart_rate_pattern": "A faster pulse can have many causes, including stress, fever, or dehydration.",
        "cholesterol_pattern": "High cholesterol usually has no symptoms and is found with a blood test.",
        "sleep_pattern": "Short or disrupted sleep can be associated with daytime sleepiness and irritability."
    }
    return contexts.get(pattern, "No context available.")